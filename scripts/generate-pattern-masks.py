"""Generate collision strips from the visible PNG silhouettes (requires Pillow).

The UV artwork fills pieces at alpha=64. Threshold the source BEFORE resizing:
thresholding resized alpha at 128 instead loses the interior and most wireframes.
Run from any directory; --check verifies the committed data matches the PNGs.
"""
import argparse
import hashlib
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'wechat-app/package-design/assets/bear-material'
OUTPUT = ROOT / 'wechat-app/utils/pattern-masks.js'
GRID = 96
NAMES = ['head', 'body', 'left-ears', 'right-ears', 'left-arm', 'right-arm']


def strips(path, grid=(GRID, GRID)):
    grid_width, grid_height = grid
    with Image.open(path) as image:
        # Include translucent fill; ignore only near-transparent antialias fringes.
        mask = image.convert('RGBA').getchannel('A').point(lambda a: 255 if a >= 16 else 0)
        mask = mask.resize(grid, Image.Resampling.BOX)
    active, result = {}, []
    for y in range(grid_height + 1):
        runs = []
        x = 0
        while y < grid_height and x < grid_width:
            if mask.getpixel((x, y)) < 128:
                x += 1
                continue
            start = x
            while x < grid_width and mask.getpixel((x, y)) >= 128:
                x += 1
            runs.append((start, x))
        for run in list(active):
            if run not in runs:
                top = active.pop(run)
                left, right = run
                result.append([[left / grid_width, top / grid_height], [right / grid_width, top / grid_height],
                               [right / grid_width, y / grid_height], [left / grid_width, y / grid_height]])
        for run in runs:
            active.setdefault(run, y)
    return result


def generate():
    sources = ', '.join(f'{name}:{hashlib.sha256((ASSETS / (name + ".png")).read_bytes()).hexdigest()[:12]}' for name in NAMES)
    data = {name: strips(ASSETS / (name + '.png')) for name in NAMES}
    return ('// Generated by scripts/generate-pattern-masks.py; includes alpha=64 filled interiors.\n'
            '// Sources: ' + sources + '\nmodule.exports = ' + json.dumps(data, separators=(',', ':')) + '\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--cushion', action='store_true', help='Generate cushion side UV silhouettes at native PNG resolution')
    args = parser.parse_args()
    if args.cushion:
        ASSETS = ROOT / 'wechat-app/package-design/assets/cushion-material'
        OUTPUT = ROOT / 'wechat-app/utils/cushion-pattern-masks.js'
        NAMES = ['side-a', 'side-b']
        data = {}
        sources = []
        for name in NAMES:
            path = ASSETS / (name + '.png')
            with Image.open(path) as image:
                size = image.size
            data['cushion_' + name.replace('-', '_')] = strips(path, size)
            sources.append(name + ':' + hashlib.sha256(path.read_bytes()).hexdigest()[:12])
        content = ('// Generated by scripts/generate-pattern-masks.py --cushion from visible UV alpha.\n'
                   '// Sources: ' + ', '.join(sources) + '\nmodule.exports = ' + json.dumps(data, separators=(',', ':')) + '\n')
    else:
        content = generate()
    if args.check:
        if OUTPUT.read_text() != content:
            raise SystemExit('Collision masks are stale. Run scripts/generate-pattern-masks.py')
        print('Collision masks match source PNGs.')
    else:
        OUTPUT.write_text(content)
        print('Generated collision masks including translucent interiors.')
